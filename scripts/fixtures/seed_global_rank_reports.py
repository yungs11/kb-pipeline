DDL = """
CREATE TABLE IF NOT EXISTS public.community_reports (
    id bigserial PRIMARY KEY, workspace_id uuid NOT NULL, level int NOT NULL,
    community_id int NOT NULL, title text NOT NULL, summary text, findings jsonb,
    rank real, entity_ids text[], created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(workspace_id, level, community_id));
"""

def main(dsn: str) -> None:
    with psycopg.connect(dsn) as c:
        c.execute(DDL)
        c.execute("DELETE FROM public.community_reports WHERE workspace_id=%s", (WS,))
        for cid, rank, title, summary, findings in REPORTS:
            c.execute(
                "INSERT INTO public.community_reports"
                " (workspace_id, level, community_id, title, summary, findings, rank)"
                " VALUES (%s,0,%s,%s,%s,%s,%s)",
                (WS, cid, title, summary, json.dumps(findings, ensure_ascii=False), rank))
        c.commit()
    print(f"리포트 {len(REPORTS)}건 주입 — workspace {WS}")


if __name__ == "__main__":
    main(sys.argv[1])
